#!/usr/bin/env bash
# post-apply-setup.sh
# Run this AFTER terraform apply completes to wire up Helm values with real AWS resource IDs.
# Usage: bash scripts/post-apply-setup.sh
# Run from: project root (c:\Users\Admin\project\terraform-project\)

set -euo pipefail

INFRA_DIR="cargotrack-v2/cargotrack-infra/environments/dev"
VALUES_FILE="helm/cargotrack/values-dev.yaml"
CLUSTER_NAME="cargotrack"
REGION="us-east-1"

echo "==> Reading terraform outputs..."
cd "$INFRA_DIR"

# Capture all outputs (non-sensitive ones only)
EKS_CLUSTER_NAME=$(terraform output -raw eks_cluster_name)
S3_BUCKET=$(terraform output -raw s3_bucket_name)
EVENT_BUS=$(terraform output -raw event_bus_name)
COMPLIANCE_QUEUE=$(terraform output -raw compliance_queue_url)
AUDIT_TABLE=$(terraform output -raw dynamodb_audit_table)
CORE_ROLE=$(terraform output -raw irsa_core_service_role_arn)
DOCS_ROLE=$(terraform output -raw irsa_document_service_role_arn)
AI_ROLE=$(terraform output -raw irsa_ai_service_role_arn)
ALB_ROLE=$(terraform output -raw irsa_alb_controller_role_arn)

echo "==> Configuring kubectl..."
aws eks update-kubeconfig --name "$EKS_CLUSTER_NAME" --region "$REGION"

echo "==> Verifying cluster nodes..."
kubectl get nodes

echo "==> Installing AWS Load Balancer Controller..."
helm repo add eks https://aws.github.io/eks-charts --force-update
helm repo update

kubectl apply -k "github.com/aws/eks-charts/stable/aws-load-balancer-controller/crds?ref=master" 2>/dev/null || true

helm upgrade --install aws-load-balancer-controller eks/aws-load-balancer-controller \
  -n kube-system \
  --set clusterName="$EKS_CLUSTER_NAME" \
  --set serviceAccount.create=true \
  --set serviceAccount.name=aws-load-balancer-controller \
  --set "serviceAccount.annotations.eks\.amazonaws\.com/role-arn=$ALB_ROLE" \
  --wait --timeout=5m

echo "==> Installing ArgoCD..."
kubectl create namespace argocd --dry-run=client -o yaml | kubectl apply -f -
helm repo add argo https://argoproj.github.io/argo-helm --force-update
helm repo update

helm upgrade --install argocd argo/argo-cd \
  -n argocd \
  --set server.service.type=LoadBalancer \
  --wait --timeout=8m

echo "==> ArgoCD admin password:"
kubectl -n argocd get secret argocd-initial-admin-secret -o jsonpath="{.data.password}" | base64 -d
echo ""

echo "==> ArgoCD server URL:"
kubectl get svc argocd-server -n argocd -o jsonpath="{.status.loadBalancer.ingress[0].hostname}"
echo ""

echo "==> Updating values-dev.yaml with terraform outputs..."
cd -  # back to project root

cat > "$VALUES_FILE" << EOF
# CargoTrack Dev Environment Values
# Auto-generated by post-apply-setup.sh — DO NOT edit manually

global:
  environment: dev
  region: $REGION
  namespace: cargotrack

image:
  pullPolicy: Always

coreService:
  tag: latest
  serviceAccount:
    roleArn: "$CORE_ROLE"

documentService:
  tag: latest
  serviceAccount:
    roleArn: "$DOCS_ROLE"

aiService:
  tag: latest
  serviceAccount:
    roleArn: "$AI_ROLE"
  env:
    MOCK_AGENT: "true"

frontend:
  tag: latest

aws:
  region: $REGION
  rdsEndpoint: "$(cd $INFRA_DIR && terraform output -raw rds_endpoint)"
  rdsDatabase: cargotrack
  rdsUsername: cargotrack
  s3BucketName: "$S3_BUCKET"
  eventBusName: "$EVENT_BUS"
  complianceQueueUrl: "$COMPLIANCE_QUEUE"
  auditTableName: "$AUDIT_TABLE"
  dbSecretArn: "$(cd $INFRA_DIR && terraform output -raw kms_key_arn | head -1 || echo '')"
  appSecretArn: ""
EOF

echo "==> values-dev.yaml updated!"

echo "==> Applying ArgoCD root Application..."
kubectl apply -f gitops/apps/root-app.yaml

echo ""
echo "====== Setup Complete ======"
echo "ArgoCD is watching: helm/cargotrack/"
echo "Push a change to trigger deploy."
echo ""
echo "Monitor ArgoCD sync:"
echo "  kubectl get applications -n argocd -w"
echo ""
echo "Monitor pods:"
echo "  kubectl get pods -n cargotrack -w"
echo ""
echo "Get Ingress ALB DNS (after pods are Running):"
echo "  kubectl get ingress -n cargotrack"
